-- 어느 자동차 대여 회사에서 대여 중인 자동차들의 정보를 담은 CAR_RENTAL_COMPANY_CAR
-- 자동차 대여 기록 정보를 담은 CAR_RENTAL_COMPANY_RENTAL_HISTORY
-- 자동차 종류 별 대여 기간 종류 별 할인 정책 정보를 담은 CAR_RENTAL_COMPANY_DISCOUNT_PLAN

SELECT DISTINCT(C.CAR_ID), C.CAR_TYPE, (100-D.DISCOUNT_RATE)*C.DAILY_FEE*30 / 100 AS FEE
FROM CAR_RENTAL_COMPANY_CAR C, CAR_RENTAL_COMPANY_RENTAL_HISTORY H, CAR_RENTAL_COMPANY_DISCOUNT_PLAN D 
WHERE C.CAR_ID = H.CAR_ID AND C.CAR_TYPE = D.CAR_TYPE 
AND D.DURATION_TYPE LIKE '30일%' 
AND 500000 <=(100-D.DISCOUNT_RATE)*C.DAILY_FEE*30 /100 AND (100-D.DISCOUNT_RATE)*C.DAILY_FEE*30 / 100 < 2000000
AND C.CAR_ID NOT IN (SELECT CAR_ID FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY WHERE START_DATE <= '2022-11-30' AND END_DATE >= '2022-11-01')
ORDER BY FEE DESC, C.CAR_TYPE ASC, C.CAR_ID DESC